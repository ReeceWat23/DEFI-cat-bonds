"""
RHODEX NatCat loss reports — Supabase store (moved off Bubble 2026-11-18).

Table: public.natcat         one row per published report (year + period)
View:  public.natcat_latest  what triggers read (product natcat_loss v3)
Migration: supabase/migrations/20261118000000_natcat_reports.sql

Figures are in billions of USD and quarterly figures are cumulative
year-to-date, as published. Multiply by 1_000_000_000 for on-chain values.

`metadata` is a free-form JSON object for extra report detail, e.g.
    {"regional_distribution": {"US": {"economic_loss_b": 80, "industry_loss_b": 30}}}

Server-side only: it uses the same service-role / secret key as
bonds.py.
"""

from __future__ import annotations

import requests

from bonds import _config, _headers

TABLE = "natcat"
LATEST_VIEW = "natcat_latest"
PERIODS = ("Q1", "Q2", "Q3", "FY")

# Columns a caller may write. gap_b / period_end are generated by the DB.
WRITABLE_COLUMNS = (
    "year", "period", "economic_loss_b", "industry_loss_b",
    "source_url", "as_of", "metadata",
)


def _request(method: str, path: str, *, params: dict | None = None,
             body=None, prefer: str | None = None) -> list[dict]:
    url, key = _config()
    headers = _headers(key)
    if prefer:
        headers["Prefer"] = prefer
    resp = requests.request(method, f"{url}/rest/v1/{path}", headers=headers,
                            params=params, json=body, timeout=10)
    if not resp.ok:
        raise requests.HTTPError(f"{resp.status_code} from Supabase: {resp.text}", response=resp)
    return resp.json() if resp.content else []


def build_report(
    year: int,
    period: str,
    economic_loss_b: float | None = None,
    industry_loss_b: float | None = None,
    source_url: str | None = None,
    as_of: str | None = None,
    metadata: dict | None = None,
) -> dict:
    if period not in PERIODS:
        raise ValueError(f"period must be one of {PERIODS}, got {period!r}")
    if economic_loss_b is None and industry_loss_b is None:
        raise ValueError("a report needs at least one of economic_loss_b / industry_loss_b")
    if metadata is not None and not isinstance(metadata, dict):
        raise ValueError("metadata must be a JSON object (dict)")
    # Only the fields the caller gave: an upsert merges what is sent, so a
    # revision of one figure must not carry empty values for the others (that
    # would overwrite the stored ones). The table's defaults fill a new row.
    report = {"year": int(year), "period": period}
    for col, val in (("economic_loss_b", economic_loss_b), ("industry_loss_b", industry_loss_b),
                     ("source_url", source_url or None), ("as_of", as_of or None),
                     ("metadata", metadata)):
        if val is not None:
            report[col] = val
    return report


def upsert_reports(reports: list[dict]) -> list[dict]:
    """
    Insert reports, or update them in place when (year, period) already
    exists, e.g. when a source revises its figures. Returns the stored rows.
    """
    for r in reports:
        unknown = set(r) - set(WRITABLE_COLUMNS)
        if unknown:
            raise ValueError(f"unknown report fields: {sorted(unknown)}")
    # One request per distinct set of fields: PostgREST fills a field that
    # some rows omit with NULL for the rows that lack it, which would wipe
    # stored values on an update.
    groups: dict[tuple, list[dict]] = {}
    for r in reports:
        groups.setdefault(tuple(sorted(r)), []).append(r)
    stored: list[dict] = []
    for body in groups.values():
        stored += _request("POST", TABLE, params={"on_conflict": "year,period"}, body=body,
                           prefer="resolution=merge-duplicates,return=representation")
    return stored


def list_reports(year: int | None = None) -> list[dict]:
    """All reports, oldest to newest (optionally one year only)."""
    params = {"select": "*", "order": "period_end.asc"}
    if year is not None:
        params["year"] = f"eq.{int(year)}"
    return _request("GET", TABLE, params=params)


def get_latest() -> dict | None:
    """The single natcat_latest row, or None if the table is empty."""
    rows = _request("GET", LATEST_VIEW, params={"select": "*"})
    return rows[0] if rows else None


if __name__ == "__main__":
    import json
    for r in list_reports():
        print(f"  {r['year']} {r['period']:>2}  economic ${r['economic_loss_b']}B  "
              f"insured ${r['industry_loss_b']}B")
    print("latest:", json.dumps(get_latest(), indent=2, default=str))
